# ندرس فلتر

def num(numb):
    # اذا القيمة حقيقة (ترو) اكبر من 10 
    if numb > 10:

        return numb

# قائمة منفصله للراقام التي ساقارنها ب اكبر من 10 
# ملاحظة: اذا الارقام اكبر من 10 فهي حقيقة (ترو) 

ns = [1,10,100,0,30,11,-9]

# نستخدم الاداة فلتر لنفصل الحقيقة عن الخطا ونرمي ب الخطا وناخذ الحقيقة
for number in filter(num, ns):

# بعد الفلتره لم يتبقئ غير الحقيقة 
# دام المتبقي حقيقه ف سينفذ الامر التالي: 

    print(number)