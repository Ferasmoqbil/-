#نسوي الفانكشن
def names(f, s, l):
    print(f"hi {f.strip().capitalize()} {s.strip().upper():.1s} {l.strip().capitalize()}")

#نساله لكل رساله لوحدها لاني فوق فصلت كل اسم من حرف f و s و l 
bruh = input("hi what's your first name?\n")
bru = input("hi what's your 2 name?\n")
brh = input("hi what's your 3 name?\n")

#نطبع الي داخل المتغيرات تبع الاسئله في اماكن ال f و s و l 
names(bruh, bru, brh)